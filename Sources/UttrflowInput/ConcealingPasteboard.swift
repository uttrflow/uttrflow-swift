public import struct Foundation.Data

/// A pasteboard that marks every text write concealed, for words the app already knows are a secret.
public struct ConcealingPasteboard: Pasteboard {
    private let base: any Pasteboard
    /// Seconds each write stays on the clipboard, read at the write so a changed setting applies; 0 is off.
    private let clearsAfter: @Sendable () -> Int
    private let clear: ConcealedClipboardClear

    /// Wraps the pasteboard the writes go through, so its announcements still happen.
    public init(
        _ base: any Pasteboard, clearingAfter seconds: @escaping @Sendable () -> Int = { 0 },
        clear: ConcealedClipboardClear = ConcealedClipboardClear()
    ) {
        self.base = base
        self.clearsAfter = seconds
        self.clear = clear
    }

    public func text() -> String? { base.text() }

    public func changeCount() -> Int? { base.changeCount() }

    public func discardContents(ifUnchangedSince changeCount: Int) -> Bool {
        base.discardContents(ifUnchangedSince: changeCount)
    }

    public func setText(_ text: String) -> PasteboardWriteResult { clearedLater(base.setConcealedText(text)) }

    /// The formatted flavour is dropped, since a concealed write carries the plain words alone.
    public func setText(_ text: String, richText: String?) -> PasteboardWriteResult {
        clearedLater(base.setConcealedText(text))
    }

    public func setConcealedText(_ text: String) -> PasteboardWriteResult {
        clearedLater(base.setConcealedText(text))
    }

    public func writeText(_ text: String, richText: String?) -> PasteboardWriteResult {
        clearedLater(base.writeConcealedText(text))
    }

    public func writeTransientText(_ text: String, richText: String?) -> PasteboardWriteResult {
        clearedLater(base.writeConcealedText(text))
    }

    public func writeAutoGeneratedText(_ text: String) -> PasteboardWriteResult {
        clearedLater(base.writeConcealedText(text))
    }

    public func writeConcealedText(_ text: String) -> PasteboardWriteResult {
        clearedLater(base.writeConcealedText(text))
    }

    public func setImage(_ data: Data) -> PasteboardWriteResult { base.setImage(data) }

    private func clearedLater(_ result: PasteboardWriteResult) -> PasteboardWriteResult {
        guard result.didWrite else { return result }
        clear.schedule(on: base, writtenAt: result.changeCount, afterSeconds: clearsAfter())
        return result
    }
}

extension ConcealingPasteboard: SnapshotRestorablePasteboard {
    func snapshot() -> PasteboardSnapshot? { (base as? any SnapshotRestorablePasteboard)?.snapshot() }

    func restore(_ snapshot: PasteboardSnapshot, ifUnchangedSince changeCount: Int) -> Bool {
        (base as? any SnapshotRestorablePasteboard)?.restore(snapshot, ifUnchangedSince: changeCount) ?? false
    }
}
