import Foundation
import Testing

@testable import UttrflowInput

@Suite("Raw item pasteboard")
struct RawItemPasteboardTests {
    private final class Board: RawItemPasteboard, @unchecked Sendable {
        var rawItems: [[String: Data]]
        var count: Int
        var discards = 0
        init(items: [[String: Data]], count: Int) { rawItems = items; self.count = count }
        func text() -> String? { nil }
        func changeCount() -> Int? { count }
        func discardContents(ifUnchangedSince changeCount: Int) -> Bool { discards += 1; return true }
        func replaceRawItems(_ items: [[String: Data]]) -> Bool { rawItems = items; return true }
        func setText(_ text: String) -> PasteboardWriteResult { .refused }
        func setConcealedText(_ text: String) -> PasteboardWriteResult { .refused }
        func writeTransientText(_ text: String, richText: String?) -> PasteboardWriteResult { .refused }
        func writeAutoGeneratedText(_ text: String) -> PasteboardWriteResult { .refused }
        func writeConcealedText(_ text: String) -> PasteboardWriteResult { .refused }
        func setImage(_ data: Data) -> PasteboardWriteResult { .refused }
    }

    private let kept: [[String: Data]] = [["public.utf8-plain-text": Data("kept".utf8)]]

    @Test("a snapshot carries the items as they are")
    func snapshotCarriesItems() {
        #expect(Board(items: kept, count: 1).snapshot() == PasteboardSnapshot(items: kept))
    }

    @Test("restoring while unchanged puts the items back")
    func restoresWhenUnchanged() {
        let board = Board(items: [], count: 4)
        #expect(board.restore(PasteboardSnapshot(items: kept), ifUnchangedSince: 4))
        #expect(board.rawItems == kept)
    }

    @Test("a newer copy is never overwritten")
    func refusesWhenChanged() {
        let board = Board(items: [], count: 5)
        #expect(!board.restore(PasteboardSnapshot(items: kept), ifUnchangedSince: 4))
        #expect(board.rawItems.isEmpty)
    }

    @Test("restoring an empty snapshot clears the board")
    func emptySnapshotClears() {
        let board = Board(items: kept, count: 4)
        #expect(board.restore(PasteboardSnapshot(items: []), ifUnchangedSince: 4))
        #expect(board.discards == 1)
    }
}
